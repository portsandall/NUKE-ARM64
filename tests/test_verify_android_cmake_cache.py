import tempfile
import unittest
from pathlib import Path

from verify_android_cmake_cache import verify_android_arm64_cache


class VerifyAndroidCMakeCacheTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.ndk = self.root / "android-ndk"
        self.toolchain = self.ndk / "build" / "cmake" / "android.toolchain.cmake"
        self.toolchain.parent.mkdir(parents=True)
        self.toolchain.write_text("# fixture\n", encoding="utf-8")
        self.cache = self.root / "CMakeCache.txt"

    def tearDown(self):
        self.temp.cleanup()

    def write_cache(self, *, system="Android", abi="arm64-v8a", ndk=None, toolchain=None):
        ndk = self.ndk if ndk is None else ndk
        toolchain = self.toolchain if toolchain is None else toolchain
        self.cache.write_text(
            "# CMake cache fixture\n"
            "// Generated by CMake\n"
            f"CMAKE_SYSTEM_NAME:INTERNAL={system}\n"
            f"CMAKE_ANDROID_ARCH_ABI:STRING={abi}\n"
            f"CMAKE_ANDROID_NDK:PATH={ndk}\n"
            f"CMAKE_TOOLCHAIN_FILE:FILEPATH={toolchain}\n",
            encoding="utf-8",
        )

    def test_accepts_android_arm64_ndk_cache(self):
        self.write_cache()
        result = verify_android_arm64_cache(self.cache)
        self.assertEqual(result["system"], "Android")
        self.assertEqual(result["abi"], "arm64-v8a")
        self.assertEqual(Path(result["ndk"]), self.ndk.resolve())

    def test_rejects_host_configure(self):
        self.write_cache(system="Linux")
        with self.assertRaisesRegex(ValueError, "CMAKE_SYSTEM_NAME"):
            verify_android_arm64_cache(self.cache)

    def test_rejects_wrong_android_abi(self):
        self.write_cache(abi="x86_64")
        with self.assertRaisesRegex(ValueError, "CMAKE_ANDROID_ARCH_ABI"):
            verify_android_arm64_cache(self.cache)

    def test_rejects_toolchain_outside_declared_ndk(self):
        other = self.root / "other" / "android.toolchain.cmake"
        other.parent.mkdir()
        other.write_text("# wrong toolchain\n", encoding="utf-8")
        self.write_cache(toolchain=other)
        with self.assertRaisesRegex(ValueError, "does not belong"):
            verify_android_arm64_cache(self.cache)

    def test_rejects_missing_cache(self):
        with self.assertRaisesRegex(ValueError, "does not exist"):
            verify_android_arm64_cache(self.root / "missing.txt")


if __name__ == "__main__":
    unittest.main()
